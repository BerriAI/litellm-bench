function hasCustomDetailCharts(benchmarkId: string): benchmarkId is keyof typeof detailCharts {
  return Object.hasOwn(detailCharts, benchmarkId);
}

type ChartTheme = ReturnType<typeof readChartTheme>;

export function overviewSpec(
  records: BenchmarkRecord[],
  theme: ChartTheme = readChartTheme(),
  annotations: readonly BenchmarkAnnotation[] = [],
  base = "",
): TopLevelSpec | null {
  const values = observations(records);
  if (!values.length) return null;
  const names = unique(values.map((item) => item.name));
  return {
    $schema: "https://vega.github.io/schema/vega-lite/v6.json",
    background: theme.colors.surface,
    config: theme.config,
    spacing: chartPresentation.spacing,
    vconcat: names.map((name) => {
      const metrics = values.filter((item) => item.name === name);
      const metric = metrics[0];
      return {
        width: "container",
        height: chartPresentation.overviewHeight,
        title: {
          text: name,
          subtitle: `${metric.label} · ${unique(metrics.map((item) => item.unit)).join(" / ")}`,
        },
        data: {
          values: metrics.map((item) => ({
            ...item,
            path: withBase(`${item.benchmarkId}/`, base),
          })),
        },
        encoding: {
          x: {
            field: "version",
            type: "ordinal",
            sort: [...uniqueVersions(values.map((item) => item.version))],
            scale: { type: "band", paddingInner: 0, paddingOuter: 0.5 },
            title: "LiteLLM version",
          },
          detail: { field: "key", type: "nominal" },
          color: {
            field: "environment",
            type: "nominal",
            title: "Configuration",
            scale: { range: theme.series },
            legend: null,
          },
        },
        layer: [
          {
            mark: { type: "line", strokeWidth: chartPresentation.lineWidth },
            encoding: {
              y: {
                aggregate: "median",
                field: "value",
                type: "quantitative",
                title: metric.unit,
                scale: { zero: false, nice: true },
              },
            },
          },
          {
            mark: {
              type: "point",
              cursor: "pointer",
              filled: true,
              size: chartPresentation.pointSize,
            },
            encoding: {
              y: {
                field: "value",
                type: "quantitative",
                title: metric.unit,
                scale: { zero: false, nice: true },
              },
              href: { field: "path" },
              tooltip: [
                { field: "name", title: "Metric" },
                { field: "version", title: "Version" },
                { field: "value", type: "quantitative", title: "Value", format: ".3~r" },
                { field: "unit", title: "Unit" },
                { field: "environment", title: "Configuration" },
              ],
            },
          },
          ...annotationLayers(
            resolveAnnotations(
              records.filter((record) => record.benchmark_id === metric.benchmarkId),
              [metric.metricId],
              annotations,
            ),
            theme.colors.foreground,
          ),
        ],
      };
    }),
  };
}

export function detailDefinitions(
  benchmarkId: string,
  records: BenchmarkRecord[],
): readonly DetailChartDefinition[] {
  const custom: readonly DetailChartDefinition[] = hasCustomDetailCharts(benchmarkId)
    ? detailCharts[benchmarkId]
    : [];
  const metrics = observations(records.filter((record) => record.benchmark_id === benchmarkId));
  const uncovered = metrics.filter((metric) =>
    !custom.some((chart) => chart.unit === metric.unit && chart.metricIds.includes(metric.metricId))
  );
  const keys = unique(uncovered.map((metric) => JSON.stringify([metric.metricId, metric.unit])));
  return [
    ...custom,
    ...keys.map((key) => {
      const metric = uncovered.find((item) => JSON.stringify([item.metricId, item.unit]) === key)!;
      return {
        title: metric.name,
        description: metric.label,
        unit: metric.unit,
        metricIds: [metric.metricId],
      };
    }),
  ];
}

export function detailSpec(
  benchmarkId: string,
  records: BenchmarkRecord[],
  definition: DetailChartDefinition,
  theme: ChartTheme = readChartTheme(),
  annotations: readonly BenchmarkAnnotation[] = [],
): TopLevelSpec | null {
  const scoped = records.filter((record) => record.benchmark_id === benchmarkId);
  const values = observations(scoped)
    .filter((metric) =>
      definition.metricIds.includes(metric.metricId) && metric.unit === definition.unit
    )
    .map((metric) => ({
      ...metric,
      series: `${metric.label}${metric.group ? ` · ${metric.group}` : ""}`,
    }));
  if (!values.length) return null;
  return {
    $schema: "https://vega.github.io/schema/vega-lite/v6.json",
    width: "container",
    height: chartPresentation.detailHeight,
    data: { values },
    config: theme.config,
    encoding: {
      x: {
        field: "version",
        type: "ordinal",
        sort: [...uniqueVersions(values.map((item) => item.version))],
        scale: { type: "band", paddingInner: 0, paddingOuter: 0.5 },
        title: "LiteLLM version",
      },
      detail: { field: "key", type: "nominal" },
      color: {
        field: "series",
        type: "nominal",
        title: null,
        scale: { range: theme.series },
        legend: { orient: "bottom", direction: "horizontal", symbolType: "stroke" },
      },
    },
    layer: [
      {
        mark: { type: "line", strokeWidth: chartPresentation.lineWidth },
        encoding: {
          strokeDash: { field: "environment", type: "nominal", legend: null },
          y: {
            aggregate: "median",
            field: "value",
            type: "quantitative",
            title: definition.unit,
            scale: { zero: false, nice: true },
          },
        },
      },
      {
        mark: { type: "point", filled: true, size: chartPresentation.pointSize },
        encoding: {
          y: {
            field: "value",
            type: "quantitative",
            title: definition.unit,
            scale: { zero: false, nice: true },
          },
          tooltip: [
            { field: "name", title: "Metric" },
            { field: "version", title: "Version" },
            { field: "value", type: "quantitative", title: "Value", format: ".3~r" },
            { field: "environment", title: "Configuration" },
          ],
        },
      },
      ...annotationLayers(
        resolveAnnotations(scoped, definition.metricIds, annotations),
        theme.colors.foreground,
      ),
    ],
  };
}
