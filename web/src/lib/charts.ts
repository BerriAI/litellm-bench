export interface DetailChartDefinition {
  description: string;
  metricIds: readonly string[];
  title: string;
  unit: string;
}

type ContractDetailChartDefinition<I extends BenchmarkId> = {
  [U in BenchmarkUnit<I>]:
    & Omit<DetailChartDefinition, "metricIds" | "unit">
    & {
      metricIds: readonly BenchmarkMetricIdForUnit<I, U>[];
      unit: U;
    };
}[BenchmarkUnit<I>];

type DetailChartRegistry = {
  [I in BenchmarkId]?: readonly ContractDetailChartDefinition<I>[];
};

